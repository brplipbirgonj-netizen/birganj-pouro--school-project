// জেলা থেকে উপজেলার তালিকা
export function getUpazilas(district: string): string[] {
  if (!district || !GEO_DATA[district]) return [];
  return Object.keys(GEO_DATA[district]).sort();
}

// উপজেলা থেকে ইউনিয়নের তালিকা
export function getUnions(district: string, upazila: string): string[] {
  if (!district || !upazila || !GEO_DATA[district]?.[upazila]) return [];
  return GEO_DATA[district][upazila].unions.sort();
}

// উপজেলা থেকে ডাকঘরের তালিকা
export function getPostOffices(district: string, upazila: string): string[] {
  if (!district || !upazila || !GEO_DATA[district]?.[upazila]) return [];
  return GEO_DATA[district][upazila].postOffices;
}
