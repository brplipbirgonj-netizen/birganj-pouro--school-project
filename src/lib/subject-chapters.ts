/**
 * Returns the list of chapters for a specific class and subject.
 */
export const getChapters = (className: string, subjectName: string): string[] => {
    // Subject names might need normalization
    const classData = CHAPTERS_DATA[className];
    if (!classData) return [];

    // Try direct match
    if (classData[subjectName]) return classData[subjectName];

    // Try common alternate names
    const alternateKeys = Object.keys(classData);
    for (const key of alternateKeys) {
        if (subjectName.includes(key) || key.includes(subjectName)) {
            return classData[key];
        }
    }

    return [];
};
